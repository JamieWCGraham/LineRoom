"use client";

import { useRef } from "react";
import { useMobileToolbarInset } from "@/lib/hooks/useMobileToolbarInset";

type Props = {
  similarArtists: string;
  genre: string;
  onSimilarArtistsChange: (v: string) => void;
  onGenreChange: (v: string) => void;
  onGenerate: () => void;
  loading: boolean;
  error: string | null;
  lyricsEmpty: boolean;
  /** e.g. "Free: 2 left" or "Pro" */
  quotaBadge?: string | null;
};

export function CritiqueSetupPanel({
  similarArtists,
  genre,
  onSimilarArtistsChange,
  onGenreChange,
  onGenerate,
  loading,
  error,
  lyricsEmpty,
  quotaBadge,
}: Props) {
  const mobileHeaderRef = useRef<HTMLDivElement>(null);
  const mobileHeaderInsetPx = useMobileToolbarInset(mobileHeaderRef);

  return (
    <div className="flex min-h-0 flex-1 flex-col overflow-hidden rounded-xl border border-zinc-800 bg-zinc-900/30 max-lg:rounded-none max-lg:border-x-0">
      <div
        ref={mobileHeaderRef}
        className="shrink-0 border-b border-zinc-800/80 px-3 py-2 max-lg:fixed max-lg:inset-x-0 max-lg:top-[var(--lineroom-mobile-top,0px)] max-lg:z-[50] max-lg:bg-zinc-950/95 max-lg:px-5 max-lg:pt-[max(0.75rem,calc(var(--lineroom-safe-top,env(safe-area-inset-top))+0.5rem))] max-lg:backdrop-blur-md lg:relative lg:z-auto lg:bg-transparent lg:px-3 lg:pb-2 lg:pt-3"
      >
        <h2 className="text-xs font-medium uppercase tracking-wide text-zinc-300">
          Before the critique
        </h2>
        <p className="mt-0.5 text-[11px] leading-snug text-zinc-600">
          Add context so the critique can use genre craft and your reference
          points.
        </p>
      </div>

      <div
        className="shrink-0 lg:hidden"
        style={{ height: mobileHeaderInsetPx }}
        aria-hidden
      />

      <div className="min-h-0 flex-1 space-y-4 overflow-y-auto overscroll-none p-3 max-lg:px-5 [touch-action:pan-y]">
        <label className="block">
          <span className="mb-1 block text-[11px] font-medium uppercase tracking-wide text-zinc-100">
           Who are the closest artists/influences for this piece?
          </span>
          <textarea
            value={similarArtists}
            onChange={(e) => onSimilarArtistsChange(e.target.value)}
            disabled={loading}
            rows={3}
            className="w-full resize-y rounded-lg border border-zinc-800 bg-zinc-900/60 p-2.5 text-sm text-zinc-100 placeholder:text-zinc-600 focus:border-emerald-700/40 focus:outline-none focus:ring-1 focus:ring-emerald-600/25 disabled:opacity-50"
            placeholder="Names or short notes on tone, era, scene…"
          />
        </label>

        <label className="block">
          <span className="mb-1 block text-[11px] font-medium uppercase tracking-wide text-zinc-100">
            What is the genre of the piece?
          </span>
          <input
            type="text"
            value={genre}
            onChange={(e) => onGenreChange(e.target.value)}
            disabled={loading}
            className="w-full rounded-lg border border-zinc-800 bg-zinc-900/60 px-3 py-2 text-sm text-zinc-100 placeholder:text-zinc-600 focus:border-emerald-700/40 focus:outline-none focus:ring-1 focus:ring-emerald-600/25 disabled:opacity-50"
            placeholder="e.g. indie folk, spoken word, sonnet, UK drill…"
          />
        </label>
      </div>

      {error ? (
        <div
          className="mx-3 mb-2 max-lg:mx-5 shrink-0 rounded-lg border border-rose-900/50 bg-rose-950/40 px-3 py-2 text-sm text-rose-200"
          role="alert"
        >
          {error}
        </div>
      ) : null}

      <div className="shrink-0 border-t border-zinc-800/80 p-3 max-lg:px-5">
        {quotaBadge ?
          <p className="mb-2 text-center text-[11px] font-medium text-zinc-500">
            {quotaBadge}
          </p>
        : null}
        <p className="mb-2 text-center text-[11px] leading-relaxed text-zinc-500">
          Critiques are generated by AI. Your lyrics are sent to our AI provider only to generate your critique.
        </p>
        <button
          type="button"
          data-tour-target="generate-critique"
          onClick={onGenerate}
          disabled={loading || lyricsEmpty}
          style={{ touchAction: "manipulation" }}
          className="w-full rounded-lg bg-emerald-700/90 px-4 py-3 text-sm font-semibold text-zinc-950 transition hover:bg-emerald-600 disabled:cursor-not-allowed disabled:opacity-40"
        >
          {loading ? (
            <span className="inline-flex items-center gap-2">
              <span
                className="h-4 w-4 animate-spin rounded-full border-2 border-zinc-950/40 border-t-zinc-950"
                aria-hidden
              />
              Generating critique...
            </span>
          ) : (
            "Generate Critique"
          )}
        </button>
        {loading ? (
          <p className="mt-2 text-center text-[11px] text-zinc-500">
            Generating a new critique can take up to 1-2 minutes.
          </p>
        ) : null}
        {lyricsEmpty ? (
          <p className="mt-2 text-center text-[11px] text-zinc-600">
            Add lyrics or poetry in the draft to enable critique.
          </p>
        ) : null}
      </div>
    </div>
  );
}
